#!/bin/sh
# Embed runtime/*.h and std/*.mxy into src/embed/embed.c
set -e

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/src/embed/embed.c"
RUNTIME="core str fmt list map obj fn future process"

escape() {
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/' "$1"
}

{
    echo "/* generated by scripts/genembed.sh — do not edit */"
    echo "#include <string.h>"
    echo "#include \"embed.h\""
    echo
    echo "static const char runtime_src[] ="
    for part in $RUNTIME; do
        escape "$ROOT/runtime/$part.h"
    done
    echo "    \"\";"
    echo
    echo "typedef struct {"
    echo "    const char *path;"
    echo "    const char *source;"
    echo "} StdEntry;"
    echo
    echo "static const StdEntry std_entries[] = {"
    for f in "$ROOT"/std/*.mxy; do
        [ -f "$f" ] || continue
        echo "    {\"std/$(basename "$f")\","
        escape "$f"
        echo "    \"\"},"
    done
    echo "};"
    echo
    echo "const char *embed_runtime(void) { return runtime_src; }"
    echo
    echo "int embed_std_count(void) { return (int)(sizeof(std_entries) / sizeof(std_entries[0])); }"
    echo
    echo "const char *embed_std_name(int index) {"
    echo "    if (index < 0 || index >= embed_std_count()) return NULL;"
    echo "    return std_entries[index].path;"
    echo "}"
    echo
    echo "const char *embed_std(const char *path) {"
    echo "    for (int i = 0; i < embed_std_count(); i++)"
    echo "        if (strcmp(std_entries[i].path, path) == 0) return std_entries[i].source;"
    echo "    return NULL;"
    echo "}"
} > "$OUT"
